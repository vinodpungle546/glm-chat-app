def test_broken_json_twice_keeps_what_came_before_the_error():
    transcript, golden = fixture("release_review")
    body = json.dumps(golden)
    assert mn.parse_json(body.replace('"risks": []', '"risks" []'))[0] == golden  # a missing colon is repaired
    cut = body[: body.index('"risks"') + 12]  # the reply stops part-way: closed, kept, and flagged
    result = mn.generate(transcript, transcript["speaker_names"], {}, lambda _m: cut)
    assert result["valid"] and "cut short" in result["warnings"][0] and len(result["notes"]["action_items"]) == 2
    broken = body.replace('"risks": []', '@@@ "risks": []')  # unrepairable, twice
    result = mn.generate(transcript, transcript["speaker_names"], {}, lambda _m: broken)
    assert not result["valid"] and result["attempts"] == 2
    assert [a["action"] for a in result["notes"]["action_items"]] == ["Finish the release notes", "Run the smoke test after the deployment"]
    assert result["notes"]["decisions"] and "didn't fully match" in result["warnings"][0]
    assert mn.salvage_json('{"a": [1, 2], "b": {"c": "x"') == {"a": [1, 2], "b": {"c": "x"}}


