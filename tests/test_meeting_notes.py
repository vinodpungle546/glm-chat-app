def test_merge_deduplicates_decisions_and_actions_across_parts():
    a = {"meeting": {"title": "x"}, "tldr": ["Release approved"], "topics": [{"title": "Release", "points": [{"text": "A"}]}],
         "decisions": [{"decision": "Ship release 4.2 on Friday", "made_by": "Cian", "timestamp": "00:10:00"}],
         "action_items": [{"action": "Retest refunds on staging", "owner": "", "due_date": "", "timestamp": "00:11:00"}],
         "details": {"standup_updates": [{"person": "Owen", "today": "Testing"}]}}
    b = {"meeting": {"title": "x"}, "tldr": ["Release approved", "Refund retest owned by Owen"],
         "topics": [{"title": "Release", "points": [{"text": "B"}]}],
         "decisions": [{"decision": "Ship the 4.2 release on Friday", "made_by": "", "timestamp": "00:42:00"}],
         "action_items": [{"action": "Retest the refunds on staging", "owner": "Owen", "due_date": "Friday", "timestamp": "00:43:00"},
                          {"action": "Update the release notes", "owner": "Cian", "due_date": "", "timestamp": "00:44:00"}],
         "details": {"standup_updates": [{"person": "Owen", "blockers": "None"}]}}
    merged = mn.merge_notes([a, b])
    assert len(merged["decisions"]) == 1 and merged["decisions"][0]["timestamp"] == "00:10:00"
    assert len(merged["action_items"]) == 2
    retest = merged["action_items"][0]
    assert retest["owner"] == "Owen" and retest["due_date"] == "Friday"  # gaps filled from the duplicate
    assert merged["tldr"] == ["Release approved", "Refund retest owned by Owen"]
    assert [p["text"] for p in merged["topics"][0]["points"]] == ["A", "B"]
    assert merged["details"]["standup_updates"] == [{"person": "Owen", "today": "Testing", "blockers": "None"}]


def test_long_meeting_is_extracted_in_parts_and_merged():
    transcript, golden = fixture("standup")
    segs = transcript["segments"]
    transcript["segments"] = [dict(s, start=s["start"] + k * 400, end=s["end"] + k * 400) for k in range(40) for s in segs]
    calls = []

    def complete(messages):
        calls.append(messages)
        return json.dumps(golden)
    events = []
    result = mn.generate(transcript, transcript["speaker_names"], {}, complete, emit=events.append, context_length=4096)
    assert result["parts"] > 1 and len(calls) >= result["parts"]
    assert any(e["type"] == "notice" and "parts" in e["text"] for e in events)
    actions = [a["action"] for a in result["notes"]["action_items"]]
    assert len(actions) == len(set(actions)) == 3  # the same items from every part, merged once


